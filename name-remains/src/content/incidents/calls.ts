import type { Effects, IncidentDef } from '../../domain/contentTypes';

const noPath = { noPath: true } as const;

function offer(id: string, title: string, place: string, eligible: IncidentDef['eligible'], text: string, prompt: string, accept: { tag: string; text: string; result: string; path: string; extra?: Effects }, declineText: string, weight = 10): IncidentDef {
  return {
    id,
    kind: 'call',
    title,
    threats: [],
    entry: 'voluntary',
    tier: 0,
    place,
    eligible,
    weight,
    repeatable: true,
    nodes: {
      entry: { kind: 'auto', text, next: 'd1' },
      d1: {
        kind: 'decision',
        prompt,
        choices: [
          {
            id: 'accept',
            tag: accept.tag,
            text: accept.text,
            check: 'rule',
            success: { text: accept.result, effects: { joinPath: { path: accept.path, tier: 1 }, ...(accept.extra ?? {}) }, end: 'accepted' },
          },
          {
            id: 'decline',
            tag: '거절',
            text: '지금은 내 삶을 그쪽으로 묶고 싶지 않다. 정중히 거절한다.',
            check: 'rule',
            success: { text: declineText, effects: { flags: { [`declined_${id}`]: true }, FAT: -4, aptChance: [{ apt: 'PRC', p: 0.1 }] }, end: 'declined' },
          },
        ],
      },
    },
  };
}

